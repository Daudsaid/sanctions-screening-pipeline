"""Evaluation: how many planted true matches does scoring catch, at what cost?

Natural true matches are too rare in this slice to measure recall, so we
plant synthetic ones. A seeded sample of OFAC person and organisation targets
(primary name in Latin script) each gets one fake subject whose name carries
one realistic change:

  persons        typo, word order, middle name dropped, middle name added,
                 transliteration variant (MOHAMMED / MUHAMMAD)
  organisations  typo, word order, UK legal suffix added (LIMITED, LTD, PLC),
                 UK or GROUP added before a legal suffix

Person plants also get a birth year and month. Half agree with the target
(true matches); half are at least two years from every target date
(negatives, since a clear birth-date conflict means a different person).
Plants carry no nationality, so nationality is neutral for them.

Plants go through the production code: matching.block.candidate_pairs against
every target name, then matching.score.score_pair with the production word
weights. A plant only counts against the target it was made from. Every real
Companies House subject is treated as a negative; their scores are read from
match_score, so run `make candidates score` first.

Writes the results tables into docs/evaluation.md between the markers below,
leaving the hand-written text around them alone.
"""

import random
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from matching.block import Name, candidate_pairs, load_names
from matching.score import load_targets, load_weights, score_pair

SEED = 20261014
PLANTS_PER_KIND = 200
THRESHOLDS = range(50, 100, 5)

PERSON_CHANGES = ("typo", "word_order", "middle_dropped", "middle_added", "transliteration")
ORG_CHANGES = ("typo", "word_order", "legal_suffix", "uk_group")

# Spellings of the same name seen across OFAC and Companies House. Each group
# is interchangeable; a plant swaps one word for another member of its group.
TRANSLITERATIONS = [
    ("MOHAMMED", "MUHAMMAD", "MOHAMMAD", "MOHAMED", "MUHAMMED"),
    ("YOUSEF", "YUSUF", "YOUSSEF", "YOUSUF"),
    ("AHMED", "AHMAD"),
    ("HUSSEIN", "HUSSAIN", "HUSAIN"),
    ("HASSAN", "HASAN"),
    ("MAHMOUD", "MAHMUD"),
    ("MUSTAFA", "MOSTAFA"),
    ("IBRAHIM", "EBRAHIM"),
    ("ISMAIL", "ESMAIL"),
    ("KHALED", "KHALID"),
    ("ABDULLAH", "ABDALLAH"),
    ("OMAR", "UMAR"),
    ("ALEKSANDR", "ALEXANDER"),
    ("ALEKSEY", "ALEXEI", "ALEKSEI"),
    ("SERGEY", "SERGEI"),
    ("ANDREY", "ANDREI"),
    ("DMITRY", "DMITRI", "DMITRIY"),
    ("NIKOLAY", "NIKOLAI"),
    ("YEVGENIY", "EVGENY", "EVGENIY"),
    ("YURIY", "YURI", "IURII"),
]
VARIANTS = {w: [v for v in group if v != w] for group in TRANSLITERATIONS for w in group}

MIDDLE_NAMES = ("JAMES", "JOHN", "MARIE", "ANNE", "EDWARD", "LOUISE", "DAVID", "ELIZABETH")
LEGAL_SUFFIXES = ("LIMITED", "LTD", "PLC")
LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"

RESULTS_START = "<!-- results:start (generated by eval/evaluate.py) -->"
RESULTS_END = "<!-- results:end -->"
DOC = Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"


# --- Name changes. Each returns the changed name, or None if it can't apply.


def typo(name: str, rng: random.Random) -> str | None:
    words = name.split()
    eligible = [i for i, w in enumerate(words) if len(w) >= 3]
    if not eligible:
        return None
    i = rng.choice(eligible)
    w = words[i]
    p = rng.randrange(len(w) - 1)
    op = rng.choice(("substitute", "delete", "transpose", "double"))
    if op == "substitute":
        new = w[:p] + rng.choice(LETTERS.replace(w[p], "")) + w[p + 1 :]
    elif op == "delete":
        new = w[:p] + w[p + 1 :]
    elif op == "transpose":
        new = w[:p] + w[p + 1] + w[p] + w[p + 2 :]
    else:
        new = w[:p] + w[p] + w[p:]
    if new == w:  # transposing a double letter changes nothing
        new = w[:p] + w[p + 1 :]
    words[i] = new
    return " ".join(words)


def word_order(name: str, rng: random.Random, kind: str) -> str | None:
    words = name.split()
    if len(set(words)) < 2:
        return None
    if kind == "person":
        # Surname first, as when a form's name fields are filled in the wrong order.
        new = words[1:] + words[:1]
    else:
        i = rng.randrange(len(words) - 1)
        new = words[:i] + [words[i + 1], words[i]] + words[i + 2 :]
    return " ".join(new) if new != words else None


def middle_dropped(name: str, rng: random.Random) -> str | None:
    words = name.split()
    if len(words) < 3:
        return None
    i = rng.randrange(1, len(words) - 1)
    return " ".join(words[:i] + words[i + 1 :])


def middle_added(name: str, rng: random.Random) -> str | None:
    words = name.split()
    if len(words) < 2:
        return None
    extra = rng.choice([m for m in MIDDLE_NAMES if m not in words])
    return " ".join(words[:1] + [extra] + words[1:])


def transliteration(name: str, rng: random.Random) -> str | None:
    words = name.split()
    eligible = [i for i, w in enumerate(words) if w in VARIANTS]
    if not eligible:
        return None
    i = rng.choice(eligible)
    words[i] = rng.choice(VARIANTS[words[i]])
    return " ".join(words)


def legal_suffix(name: str, rng: random.Random) -> str | None:
    return f"{name} {rng.choice(LEGAL_SUFFIXES)}"


def uk_group(name: str, rng: random.Random) -> str | None:
    words = name.split()
    options = [w for w in ("UK", "GROUP") if w not in words]
    if not options:
        return None
    return f"{name} {rng.choice(options)} {rng.choice(LEGAL_SUFFIXES)}"


def apply_change(change: str, name: str, kind: str, rng: random.Random) -> str | None:
    if change == "word_order":
        return word_order(name, rng, kind)
    return {
        "typo": typo,
        "middle_dropped": middle_dropped,
        "middle_added": middle_added,
        "transliteration": transliteration,
        "legal_suffix": legal_suffix,
        "uk_group": uk_group,
    }[change](name, rng)


def plant_dob(target_dates: list[str], agree: bool, rng: random.Random) -> tuple[int, int]:
    """A Companies House style (year, month) that agrees or clearly conflicts."""
    if agree:
        d = rng.choice(target_dates)
        month = int(d[5:7]) if len(d) >= 7 else rng.randint(1, 12)
        return int(d[:4]), month
    years = [int(d[:4]) for d in target_dates]
    while True:
        year = rng.choice(years) + rng.choice((-1, 1)) * rng.randint(3, 15)
        if all(abs(year - y) >= 2 for y in years):
            return year, rng.randint(1, 12)


# --- Plants


@dataclass
class Plant:
    plant_id: str
    kind: str
    target_id: str
    change: str
    source: str  # target name the plant was made from
    raw: str  # plant name before legal forms are stripped
    is_true: bool
    dob: tuple[int, int] | None = None
    core: str = ""  # plant name as matching sees it


def make_plants(
    kind: str,
    sources: list[tuple[str, str, list[str]]],
    rng: random.Random,
    n: int = PLANTS_PER_KIND,
) -> list[Plant]:
    """Spread n plants evenly over the change types, one target each.

    sources: (target_id, normalised primary name, birth dates), sorted.
    """
    changes = PERSON_CHANGES if kind == "person" else ORG_CHANGES
    pool = list(sources)
    rng.shuffle(pool)
    used: set[str] = set()
    plants = []
    for c_idx, change in enumerate(changes):
        quota = n // len(changes) + (c_idx < n % len(changes))
        made = 0
        for target_id, name, dates in pool:
            if made == quota:
                break
            if target_id in used:
                continue
            raw = apply_change(change, name, kind, rng)
            if raw is None or raw == name:
                continue
            used.add(target_id)
            plant = Plant(
                plant_id=f"plant-{kind}-{len(plants):03d}",
                kind=kind,
                target_id=target_id,
                change=change,
                source=name,
                raw=raw,
                is_true=True,
                core=raw,
            )
            if kind == "person":
                plant.is_true = made % 2 == 0
                plant.dob = plant_dob(dates, plant.is_true, rng)
            plants.append(plant)
            made += 1
    return plants


def score_plants(
    plants: list[Plant],
    targets: list[Name],
    weights: dict[str, float],
    target_info: dict[str, tuple[list[str], set[str]]],
    use_dob: bool = True,
) -> dict[str, float]:
    """Each plant's score against its own target; 0 if never a candidate.

    use_dob=False scores as if the subject had no birth date, as for
    officers that Companies House holds without one.
    """
    by_id = {p.plant_id: p for p in plants}
    target_name = {t.name_id: t for t in targets}
    subjects = [Name(p.plant_id, p.plant_id, p.core) for p in plants]
    name_pairs: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for c in candidate_pairs(subjects, targets):
        p, t = by_id[c.subject_name_id], target_name[c.target_name_id]
        if t.entity_id == p.target_id:
            name_pairs[p.plant_id].append((p.core, t.text))

    scores = {}
    for p in plants:
        if not name_pairs[p.plant_id]:
            scores[p.plant_id] = 0.0
            continue
        dates, countries = target_info[p.target_id]
        scores[p.plant_id] = score_pair(
            name_pairs[p.plant_id],
            weights,
            p.kind,
            subject_dob=(p.dob if use_dob else None) or (None, None),
            target_dates=dates,
            target_nat=countries,
        ).score
    return scores


# --- Summary


def change_label(p: Plant) -> str:
    return f"{'person' if p.kind == 'person' else 'org'} {p.change.replace('_', ' ')}"


def summarise(
    plants: list[Plant],
    scores: dict[str, float],
    real_scores: list[tuple[str, float]],
    name_only: dict[str, float],
    thresholds=THRESHOLDS,
) -> dict:
    """name_only: person plant scores without birth dates."""
    true = [p for p in plants if p.is_true]
    conflict = [p for p in plants if not p.is_true]
    groups: dict[str, list[Plant]] = defaultdict(list)
    for p in true:
        groups[change_label(p)].append(p)

    def recall(ps: list[Plant], t: int, by: dict[str, float] = scores) -> float:
        return sum(by[p.plant_id] >= t for p in ps) / len(ps) if ps else float("nan")

    true_person = [p for p in true if p.kind == "person"]

    rows = []
    for t in thresholds:
        rows.append(
            {
                "threshold": t,
                "recall": recall(true, t),
                "recall_person": recall(true_person, t),
                "recall_person_name_only": recall(true_person, t, name_only),
                "recall_org": recall([p for p in true if p.kind == "organization"], t),
                "real_person": sum(s >= t for k, s in real_scores if k == "person"),
                "real_org": sum(s >= t for k, s in real_scores if k == "organization"),
                "conflict": sum(scores[p.plant_id] >= t for p in conflict),
                "by_change": {g: recall(ps, t) for g, ps in groups.items()},
            }
        )
    return {
        "rows": rows,
        "n_true": len(true),
        "n_true_person": sum(p.kind == "person" for p in true),
        "n_true_org": sum(p.kind == "organization" for p in true),
        "n_conflict": len(conflict),
        "n_real": len(real_scores),
        "group_sizes": {g: len(ps) for g, ps in groups.items()},
        "not_candidates": {g: sum(scores[p.plant_id] == 0 for p in ps) for g, ps in groups.items()},
    }


def render(summary: dict) -> str:
    pct = "{:.0%}".format
    lines = [
        RESULTS_START,
        "",
        (
            f"Seed {SEED}. {summary['n_true']} true plants ({summary['n_true_person']} person, "
            f"{summary['n_true_org']} organisation), {summary['n_conflict']} person plants "
            f"with a conflicting birth date, {summary['n_real']} scored real subject-target "
            "pairs."
        ),
        "",
        (
            "| Threshold | Recall, all | Recall, persons | Recall, persons without DOB "
            "| Recall, orgs | Real alerts, persons | Real alerts, orgs | DOB-conflict alerts |"
        ),
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in summary["rows"]:
        lines.append(
            f"| {r['threshold']} | {pct(r['recall'])} | {pct(r['recall_person'])} "
            f"| {pct(r['recall_person_name_only'])} | {pct(r['recall_org'])} | {r['real_person']} | {r['real_org']} "
            f"| {r['conflict']} of {summary['n_conflict']} |"
        )
    groups = sorted(summary["group_sizes"])
    thresholds = [r["threshold"] for r in summary["rows"]]
    lines += [
        "",
        "Recall per change type (true plants only; person plants include the birth-date bonus):",
        "",
        "| Change | n | Not a candidate | " + " | ".join(map(str, thresholds)) + " |",
        "|---|---:|---:|" + "---:|" * len(thresholds),
    ]
    for g in groups:
        cells = " | ".join(pct(r["by_change"][g]) for r in summary["rows"])
        lines.append(
            f"| {g} | {summary['group_sizes'][g]} | {summary['not_candidates'][g]} | {cells} |"
        )
    lines += ["", RESULTS_END]
    return "\n".join(lines)


def write_results(doc: Path, results: str) -> None:
    """Replace the generated block in doc, keeping the text around it."""
    text = doc.read_text() if doc.exists() else ""
    if RESULTS_START in text and RESULTS_END in text:
        head, rest = text.split(RESULTS_START, 1)
        tail = rest.split(RESULTS_END, 1)[1]
        text = head + results + tail
    else:
        text = (text.rstrip() + "\n\n" if text else "# Evaluation\n\n") + results + "\n"
    doc.write_text(text)


# --- Database


def load_sources(conn, kind: str) -> list[tuple[str, str, list[str]]]:
    """Targets whose primary name survives normalisation (Latin script)."""
    rows = conn.execute(
        """
        select t.target_id, min(n.name_core), t.birth_dates
        from stg_sanctions_target t
        join int_name_norm n
          on n.side = 'target' and n.entity_id = t.target_id and n.name_raw = t.primary_name
        where t.entity_group = %s
        group by t.target_id, t.birth_dates
        order by t.target_id
        """,
        (kind,),
    ).fetchall()
    if kind == "person":
        rows = [r for r in rows if r[2]]  # birth dates needed to agree or conflict
    return [(t, name, dates or []) for t, name, dates in rows]


def strip_legal_forms(conn, names: list[str]) -> list[str]:
    """Organisation name_core as int_name_norm computes it (same seed, same regex)."""
    rows = conn.execute(
        r"""
        with forms as (
            select
                string_agg(phrase, '|' order by length(phrase) desc)
                    filter (where position in ('prefix', 'both')) as prefix_re,
                string_agg(phrase, '|' order by length(phrase) desc)
                    filter (where position in ('suffix', 'both')) as suffix_re
            from legal_forms
        )
        select coalesce(
            nullif(trim(regexp_replace(
                regexp_replace(n.name, '^((' || f.prefix_re || ')\s+)+', ''),
                '(\s+(' || f.suffix_re || '))+$', ''
            )), ''),
            n.name
        )
        from unnest(%s::text[]) with ordinality as n(name, ord)
        cross join forms f
        order by n.ord
        """,
        (names,),
    ).fetchall()
    return [r[0] for r in rows]


def run() -> None:
    from ingest.loader import get_connection

    conn = get_connection()
    real_scores = conn.execute("select entity_kind, score from match_score").fetchall()
    if not real_scores:
        raise SystemExit("match_score is empty: run `make candidates score` first")

    weights = load_weights(conn)
    target_info = load_targets(conn)
    rng = random.Random(SEED)

    plants, scores, name_only = [], {}, {}
    for kind in ("person", "organization"):
        kind_plants = make_plants(kind, load_sources(conn, kind), rng)
        if kind == "organization":
            cores = strip_legal_forms(conn, [p.raw for p in kind_plants])
            for p, core in zip(kind_plants, cores, strict=True):
                p.core = core
        targets = load_names(conn, "target", kind)
        scores |= score_plants(kind_plants, targets, weights[kind], target_info)
        if kind == "person":
            name_only = score_plants(
                kind_plants, targets, weights[kind], target_info, use_dob=False
            )
        plants += kind_plants

    summary = summarise(plants, scores, real_scores, name_only)
    results = render(summary)
    write_results(DOC, results)
    print(results)

    print("\nTrue plants scoring below 80:")
    for p in sorted(plants, key=lambda p: scores[p.plant_id]):
        if p.is_true and scores[p.plant_id] < 80:
            print(f"  {scores[p.plant_id]:5.1f}  {change_label(p):24} {p.core} / {p.source}")


if __name__ == "__main__":
    run()
